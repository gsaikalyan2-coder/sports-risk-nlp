@dataclass(frozen=True)
class MatchDayScenario:
    """The three dropdown choices, together and validated."""

    sport: str
    timing: str
    life_context: str

    def __post_init__(self) -> None:
        if self.sport not in SPORTS:
            raise ValueError(f"unknown sport {self.sport!r}; must be one of {SPORTS}")
        if self.timing not in TIMINGS:
            raise ValueError(f"unknown timing {self.timing!r}; must be one of {TIMINGS}")
        if self.life_context not in LIFE_CONTEXTS:
            raise ValueError(
                f"unknown life_context {self.life_context!r}; must be one of {LIFE_CONTEXTS}"
            )


