"""Match-day scenarios: pressure/life-context combinations for synthetic demo text.

Why this exists
----------------
The Match-day profile page (`dashboard/pages/6_Match_day_profile.py`) scores a
real press conference only when `SRN_MATCHDAY_REAL_ATHLETES` is set -- declined
by owner decision, `docs/phase29_decision_draft.md`, 2026-09-20. This module
gives that page something honest to score in the meantime: a scenario the
reader picks from dropdowns, generated by the same seeded template grammar
that produced every `synth_precomp_v1-*` example (`src/ingestion/synthetic.py`)
-- reproducible, zero-cost, no LLM, no real athlete.

Reuse, not modification
------------------------
`synthetic.py`'s own version history is explicit that changing its
construct-drawing or realisation logic reshuffles the RNG stream for every
existing corpus artefact seeded against it. This module therefore imports the
realisation banks and the framing/variation helpers UNCHANGED and adds exactly
one new mechanism: a `life_context -> construct bias` table that decides which
constructs a scenario plants and at what intensity or label, so two different
dropdown combinations produce a visibly different construct set -- not just a
different label on the same generic text. `synthetic.py` itself is untouched;
`generate_records` and every seed-42 fixture built against it are unaffected.

Grounding for the bias table
-----------------------------
Every construct named below cites the same `config/taxonomy.yaml` instrument
anchor that construct already carries in `synthetic.py`'s own realisation
bank, so this table is "grounded in the same instruments," not invented fresh
for this feature.

Why "timing," not "during or after the event"
-----------------------------------------------
`synthetic.py`'s docstring records that the Phase 7 source survey deliberately
excluded post-match text: it expresses relief, disappointment and attribution
-- constructs outside this project's taxonomy. Offering a "during" or "after"
option here would either need new taxonomy work or silently generate text the
taxonomy cannot score meaningfully. `TIMINGS` therefore stays entirely on the
pre-competition side, varying only the distance from the event.
"""

